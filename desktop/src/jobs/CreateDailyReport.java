package jobs;

import enums.NotificationType;
import records.Settings;
import records.Report;
import utils.Conn;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStreamReader;
import java.math.BigDecimal;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.time.LocalDate;
import java.time.OffsetDateTime;
import java.util.concurrent.Executors;
import java.util.concurrent.ScheduledExecutorService;
import java.util.concurrent.TimeUnit;

public class CreateDailyReport {

    private static Connection conn;

    public static void run(Settings settings) throws IOException, SQLException {
        conn = Conn.getConnection();

        ScheduledExecutorService scheduler = Executors.newScheduledThreadPool(1);

        long now = System.currentTimeMillis();
        long nextMidnight = LocalDate.now().plusDays(1).atStartOfDay(java.time.ZoneId.systemDefault()).toInstant().toEpochMilli();
        long delay = nextMidnight - now;

        scheduler.scheduleAtFixedRate(() -> {
            try {
                create(settings);
            }

            catch (SQLException | IOException | InterruptedException e) {
                e.printStackTrace();
            }
        }, delay, 24, TimeUnit.HOURS);
    }

    private static void create(Settings settings) throws SQLException, IOException, InterruptedException {
        if (!settings.autoGenerateDailyReport()) return;

        System.out.println("Creating Daily Report");

        LocalDate reportDate = LocalDate.now();

        int totalRooms = 0;
        int occupied = 0;
        int available = 0;
        int maintenance = 0;

        try (PreparedStatement ps = conn.prepareStatement("""
            select
                count(*) as total,
                count(*) filter (where roomstatus = 'occupied') as occupied,
                count(*) filter (where roomstatus = 'available') as available,
                count(*) filter (where roomstatus = 'maintenance') as maintenance
            from rooms
        """)) {
            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    totalRooms = rs.getInt("total");
                    occupied = rs.getInt("occupied");
                    available = rs.getInt("available");
                    maintenance = rs.getInt("maintenance");
                }
            }
        }

        int arrivals = 0;
        int departures = 0;
        int inHouse = 0;

        try (PreparedStatement ps = conn.prepareStatement("""
            select
                count(*) filter (where check_in_date = ?) as arrivals,
                count(*) filter (where check_out_date = ?) as departures,
                count(*) filter (where booking_status = 'CHECKED_IN') as in_house
            from bookings
        """)) {
            ps.setObject(1, reportDate);
            ps.setObject(2, reportDate);

            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    arrivals = rs.getInt("arrivals");
                    departures = rs.getInt("departures");
                    inHouse = rs.getInt("in_house");
                }
            }
        }

        BigDecimal revenue = BigDecimal.ZERO;

        try (PreparedStatement ps = conn.prepareStatement("""
            select coalesce(sum(amount), 0) as revenue from payments
            where paymentstatus = 'completed' and paymentdate::date = ?
        """)) {
            ps.setObject(1, reportDate.minusDays(1));

            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    revenue = rs.getBigDecimal("revenue");
                }
            }
        }

        int tasksCreated = 0;
        int tasksCompleted = 0;

        try (PreparedStatement ps = conn.prepareStatement("""
            select
                count(*) filter (where created_at::date = ?) as created,
                count(*) filter (where completed_at::date = ?) as completed
            from servicetasks
        """)) {
            ps.setObject(1, reportDate);
            ps.setObject(2, reportDate);

            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    tasksCreated = rs.getInt("created");
                    tasksCompleted = rs.getInt("completed");
                }
            }
        }

        int reportId;

        conn.setAutoCommit(false);

        try {
            try (PreparedStatement ps = conn.prepareStatement("""
                insert into reports (
                    report_date, total_rooms, occupied_rooms, available_rooms, maintenance_rooms,
                    arrivals, departures, in_house, revenue, tasks_created, tasks_completed
                ) values (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                on conflict (report_date) do update set
                    total_rooms = excluded.total_rooms,
                    occupied_rooms = excluded.occupied_rooms,
                    available_rooms = excluded.available_rooms,
                    maintenance_rooms = excluded.maintenance_rooms,
                    arrivals = excluded.arrivals,
                    departures = excluded.departures,
                    in_house = excluded.in_house,
                    revenue = excluded.revenue,
                    tasks_created = excluded.tasks_created,
                    tasks_completed = excluded.tasks_completed,
                    updated_at = now()
                returning id
            """)) {

                ps.setObject(1, reportDate);
                ps.setInt(2, totalRooms);
                ps.setInt(3, occupied);
                ps.setInt(4, available);
                ps.setInt(5, maintenance);
                ps.setInt(6, arrivals);
                ps.setInt(7, departures);
                ps.setInt(8, inHouse);
                ps.setBigDecimal(9, revenue);
                ps.setInt(10, tasksCreated);
                ps.setInt(11, tasksCompleted);

                try (ResultSet rs = ps.executeQuery()) {
                    rs.next();
                    reportId = rs.getInt("id");
                }
            }

            try (PreparedStatement ps = conn.prepareStatement("insert into notifications (type, title, message) values (?::notificationtype, ?, ?)")) {
                ps.setString(1, NotificationType.daily_report.name());
                ps.setString(2, "Daily Report");
                ps.setString(3, "Daily report generated for " + reportDate + ".");
                ps.executeUpdate();
            }

            conn.commit();
        }

        catch (SQLException e) {
            conn.rollback();
            throw e;
        }

        finally {
            conn.setAutoCommit(true);
        }

        Report report = new Report(
                reportId,
                reportDate,
                totalRooms,
                occupied,
                available,
                maintenance,
                arrivals,
                departures,
                inHouse,
                revenue,
                tasksCreated,
                tasksCompleted,
                OffsetDateTime.now(),
                OffsetDateTime.now()
        );

        createPhysical(report);
    }

    private static void createPhysical(Report report) throws IOException, InterruptedException {
        Path projectRoot = Paths.get(System.getProperty("user.dir")).getParent();
        Path script = projectRoot.resolve("pyutils").resolve("report_pdf.py");
        Path outDir = projectRoot.resolve("resources").resolve("records");

        Files.createDirectories(outDir);

        ProcessBuilder pb = new ProcessBuilder(
                "python",
                script.toAbsolutePath().toString(),
                String.valueOf(report.id()),
                report.reportDate().toString(),
                String.valueOf(report.totalRooms()),
                String.valueOf(report.occupiedRooms()),
                String.valueOf(report.availableRooms()),
                String.valueOf(report.maintenanceRooms()),
                String.valueOf(report.arrivals()),
                String.valueOf(report.departures()),
                String.valueOf(report.inHouse()),
                report.revenue().toString(),
                String.valueOf(report.tasksCreated()),
                String.valueOf(report.tasksCompleted()),
                outDir.toAbsolutePath().toString()
        );
        pb.redirectErrorStream(true);

        Process p = pb.start();

        try (BufferedReader reader = new BufferedReader(new InputStreamReader(p.getInputStream()))) {
            String line;
            while ((line = reader.readLine()) != null) {
                System.out.println("[pdf] " + line);
            }
        }

        int exit = p.waitFor();

        if (exit != 0) {
            throw new RuntimeException("PDF generation failed (exit " + exit + ")");
        }
    }
}