                                        id int primary key default 1,
                                        hotel_name text not null,
                                        hotel_email text not null,
                                        hotel_phone text not null,
                                        hotel_street text not null,
                                        hotel_city text not null,
                                        hotel_province text not null,
                                        hotel_postal_code text not null,
                                        hotel_country text not null,
                                        check_in_time time not null,
                                        check_out_time time not null,
                                        early_check_in_time time,
                                        late_check_out_time time,
                                        min_nights int not null default 1,
                                        max_nights int not null default 30,
                                        cancellation_window_hours int not null default 24,
                                        advance_booking_limit_days int not null default 365,
                                        pets_allowed boolean not null default false,
                                        smoking_allowed boolean not null default false,
                                        children_allowed boolean not null default true,
                                        id_required boolean not null default true,
                                        vat_rate numeric(5,2) not null default 15.00,
                                        service_charge_rate numeric(5,2) not null default 0.00,
                                        tourism_levy numeric(10,2) not null default 0.00,
                                        prices_include_vat boolean not null default true,
                                        show_tax_breakdown boolean not null default true,
                                        payment_window_minutes int not null default 30,
                                        auto_cancel_unpaid boolean not null default true,
                                        require_full_prepayment boolean not null default true,
                                        allow_deposit_payment boolean not null default false,
                                        notify_reservation_received boolean not null default true,
                                        notify_payment_confirmation boolean not null default true,
                                        notify_reservation_cancelled boolean not null default true,
