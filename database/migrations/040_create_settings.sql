                                        notify_checkout_reminder boolean not null default false,
                                        notify_feedback_request boolean not null default true,
                                        notify_staff_new_reservation boolean not null default true,
                                        notify_staff_new_payment boolean not null default true,
                                        notify_staff_task_completed boolean not null default false,
                                        notify_staff_low_occupancy boolean not null default true,
                                        notify_staff_payment_failure boolean not null default true,
                                        housekeeping_task_time time not null default '08:00',
                                        housekeeping_default_status text not null default 'pending',
