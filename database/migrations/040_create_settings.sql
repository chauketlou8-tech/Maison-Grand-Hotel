                                        auto_generate_daily_report boolean not null default true,
                                        email_daily_report boolean not null default true,
                                        report_recipient text not null default 'management@masonhotel.com',
                                        date_format text not null default 'DD/MM/YYYY',
                                        time_format text not null default '24-hour',
                                        created_at timestamptz not null default now(),
                                        updated_at timestamptz not null default now(),
                                        constraint settings_single_row check (id = 1)
);